/** A built-in extension as read, with its bundle's name. */
export interface ReadBuiltIn {
  found: ExtensionPackage
  bundle: string
}

/** A built-in extension whose manifest was refused, and the rule it broke, as `extension.manifestRefused` says. */
export interface RefusedBuiltIn {
  extension: string
  rule: ManifestRule | "invalid"
  message: string
}

/** The built-in extensions read, and those refused. */
export interface BuiltInsRead {
  read: ReadBuiltIn[]
  refused: RefusedBuiltIn[]
}

/** Reads each built-in extension's manifest, as one of the built-in list's, leaving out those refused. */
export function readBuiltIns(list: readonly BuiltInExtension[] = builtInExtensions): BuiltInsRead {
  const read: ReadBuiltIn[] = []
  const refused: RefusedBuiltIn[] = []

  for (const { packageJson, bundle } of list) {
    try {
      read.push({ found: readExtension(packageJson, { builtIn: true }), bundle })
    } catch (error) {
      refused.push(refusal(packageJson.name, error))
    }
  }

  // Two that bring the room are both refused, so there's never a second `sync.onOpen`.
  const synced = refuseSecondSync(read.map((each) => each.found))

  return {
    read: read.filter((each) => synced.kept.includes(each.found)),
    refused: [...refused, ...synced.refused.map((error) => refusal(error.extension, error))]
  }
}

// oxlint-disable-next-line anti-slop/no-unknown-parameters -- whatever readExtension threw
function refusal(extension: string, error: unknown): RefusedBuiltIn {
  return {
    extension,
    rule: error instanceof ManifestRefused ? error.rule : "invalid",
    message: error instanceof Error ? error.message : String(error)
  }
}

/** The bundles of built-in Node halves beside the service, as `extensions/vite`, each by its package's specifier. */
export function nodeHalfEntries(read: readonly ReadBuiltIn[] = readBuiltIns().read): Record<string, string> {
  return Object.fromEntries(
    read.flatMap(({ found, bundle }) => (found.main === undefined ? [] : [[`extensions/${bundle}`, found.id]]))
  )
}

/** What the page runtime's bundle beside the service is called. */
export const pageRuntimeBundle = "page-runtime"

/** What the bundle of an extension's page module beside the service is called, by the extension's prefix. */
export function pageModuleBundle(extension: string): string {
  return `page/${extension}`
}

/**
 * The bundles of what runs in the app's own page when the canvas draws a route (PAR-1260): the page runtime, and each
 * built-in extension's page modules, by their packages' specifiers.
 */
export function pageEntries(read: readonly ReadBuiltIn[] = readBuiltIns().read) {
  const modules = read.flatMap(({ found }) => {
    const { router, renderer } = found.manifest.contributes.providers ?? {}

    return [router?.page, renderer?.page].flatMap((page): [string, string][] =>
      page ? [[pageModuleBundle(found.manifest.prefix), packageExport(found.id, page.import)]] : []
    )
  })

  return { [pageRuntimeBundle]: "@parity-app/page-runtime", ...Object.fromEntries(modules) }
}

/** The window modules the window's build compiles, by extension, each as its package export's specifier. */
export function windowModuleEntries(read: readonly ReadBuiltIn[] = readBuiltIns().read): Record<string, string> {
  return Object.fromEntries(
    read.flatMap(({ found }) => {
      const { window } = found.manifest

      return window === undefined ? [] : [[found.id, `${found.id}${window.slice(1)}`]]
    })
  )
}

/**
 * `renderer/window-module-list.ts`, which the window loads its window modules through: each extension's, by its id, as
 * a function that loads its chunk. `built-in-extensions.test.ts` checks the file is this, and writes it with `-u`.
 */
export function windowModulesSource(entries: Record<string, string> = windowModuleEntries()): string {
  const loaders = Object.entries(entries).map(
    ([extension, specifier]) => `  ${JSON.stringify(extension)}: () => import(${JSON.stringify(specifier)})`
  )

  const list = loaders.length > 0 ? `{\n${loaders.join(",\n")}\n}` : "{}"

  return [
    "// Generated from src/shared/built-in-extensions.ts. After changing that list, run",
    "// `pnpm exec vp test run apps/desktop/src/shared/built-in-extensions.test.ts -u` to write it again.",
    "",
    "/** Internal extensions' window modules, by extension id, each loading its chunk when its extension activates. */",
    `export const windowModules: Record<string, () => Promise<object>> = ${list}`,
    ""
  ].join("\n")
}
